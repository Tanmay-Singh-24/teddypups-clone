// Dumps every distinct inline SVG from the captured pages into docs/reference/svg/, named after the
// nearest tp-*/pup-* class, plus an INDEX.md. Source material for the art components (src/components/art).
// Run: node scripts/extract-svgs.mjs
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { HTML_DIR, parsePage, REF_DIR } from "./lib/reference.mjs";

const OUT = path.join(REF_DIR, "svg");
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const ownClass = (el) => (el.getAttribute?.("class") ?? "").split(/\s+/).find((c) => /^(tp|pup)-/.test(c));

function nameFor(svg) {
  const own = ownClass(svg);
  if (own) return own;
  for (let el = svg.parentNode; el && el.tagName; el = el.parentNode) {
    const cls = ownClass(el);
    if (cls) return `${cls}--child`;
  }
  return "untagged";
}

// Skip the 300 near-identical puppy-page variants; one of each page type is enough.
const pages = readdirSync(HTML_DIR)
  .map((f) => f.replace(/\.html$/, ""))
  .filter((p) => !p.startsWith("puppies__") || ["puppies__maltipoo-max-male", "puppies__pomeranian-ace-boy"].includes(p))
  .filter((p) => !p.includes("__q_") && !p.startsWith("_404"));

const seen = new Map(); // hash -> entry
const byName = new Map(); // name -> count of distinct variants

for (const page of pages) {
  for (const svg of parsePage(page).querySelectorAll("svg")) {
    if (svg.parentNode?.closest?.("svg")) continue; // nested svg: part of its parent's art
    const markup = svg.toString();
    const hash = createHash("sha1").update(markup).digest("hex").slice(0, 10);
    const existing = seen.get(hash);
    if (existing) {
      existing.pages.add(page);
      existing.uses++;
      continue;
    }
    const base = nameFor(svg);
    const n = (byName.get(base) ?? 0) + 1;
    byName.set(base, n);
    const file = `${base}${n > 1 ? `-${n}` : ""}.svg`;
    writeFileSync(path.join(OUT, file), markup + "\n");
    seen.set(hash, { file, viewBox: svg.getAttribute("viewBox") ?? "", bytes: markup.length, pages: new Set([page]), uses: 1 });
  }
}

const rows = [...seen.values()].sort((a, b) => a.file.localeCompare(b.file));
const index = [
  "# Reference SVG artwork",
  "",
  "Generated by `scripts/extract-svgs.mjs`. Each file is one distinct inline SVG, named after its own or nearest `tp-*`/`pup-*` class.",
  "",
  "| File | viewBox | Bytes | Uses | Pages |",
  "|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.file} | ${r.viewBox} | ${r.bytes} | ${r.uses} | ${[...r.pages].join(", ")} |`),
  "",
].join("\n");
writeFileSync(path.join(OUT, "INDEX.md"), index);
console.log(`${rows.length} distinct SVGs from ${pages.length} pages → docs/reference/svg/`);
